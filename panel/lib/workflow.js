// Builds the GitHub Actions workflow. The cron lines are generated from the
// posting times in the panel (converted from local time to UTC, covering both
// summer and winter time so daylight saving changes never break the schedule).

function tzOffsetMinutes(timeZone, date) {
  const dtf = new Intl.DateTimeFormat("en-US", {
    timeZone, hourCycle: "h23", year: "numeric", month: "2-digit", day: "2-digit",
    hour: "2-digit", minute: "2-digit",
  });
  const p = Object.fromEntries(dtf.formatToParts(date).map((x) => [x.type, x.value]));
  const asUtc = Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour % 24, +p.minute);
  return Math.round((asUtc - date.getTime()) / 60000);
}

function cronLines(times, timeZone) {
  const year = new Date().getUTCFullYear();
  const offsets = [...new Set([0, 6].map((m) => tzOffsetMinutes(timeZone, new Date(Date.UTC(year, m, 15, 12)))))];
  const byMinute = new Map();
  for (const t of times) {
    const [h, m] = t.split(":").map(Number);
    for (const off of offsets) {
      const utc = (((h * 60 + m - off) % 1440) + 1440) % 1440;
      const minute = utc % 60;
      const hour = Math.floor(utc / 60);
      if (!byMinute.has(minute)) byMinute.set(minute, new Set());
      byMinute.get(minute).add(hour);
    }
  }
  const lines = [];
  for (const [minute, hours] of [...byMinute.entries()].sort((a, b) => a[0] - b[0])) {
    lines.push(`    - cron: "${minute} ${[...hours].sort((a, b) => a - b).join(",")} * * *"`);
  }
  return lines.length ? lines : ['    - cron: "0 0 1 1 *"'];
}

function buildWorkflow(settings) {
  const crons = cronLines(settings.times || [], settings.timezone || "Europe/Bucharest").join("\n");
  const when = "steps.due.outputs.run == 'true'";
  return `# Generated by the Velosyntech panel. Edit the schedule from the panel, not here.
name: Instagram auto-post
run-name: \${{ github.event_name == 'workflow_dispatch' && format('Manual - {0}', inputs.mode) || 'Programat' }}

on:
  schedule:
${crons}
  workflow_dispatch:
    inputs:
      mode:
        description: "now = postează acum, test = doar video (fără postare)"
        type: choice
        options: [test, now]
        default: test

permissions:
  contents: write

concurrency:
  group: instagram-post
  cancel-in-progress: false

jobs:
  post:
    runs-on: ubuntu-latest
    timeout-minutes: 40
    steps:
      - uses: actions/checkout@v4

      - name: Is a post due?
        id: due
        run: python3 -m autoposter.due "\${{ github.event_name }}" "\${{ inputs.mode }}"

      - if: ${when}
        uses: actions/setup-python@v5
        with:
          python-version: "3.12"
          cache: pip

      - if: ${when}
        name: Install
        run: |
          sudo apt-get update -qq
          sudo apt-get install -y -qq ffmpeg fonts-inter
          pip install -q -r requirements.txt

      - if: ${when}
        name: Make video + post
        env:
          GEMINI_API_KEY: \${{ secrets.GEMINI_API_KEY }}
          GROQ_API_KEY: \${{ secrets.GROQ_API_KEY }}
          PEXELS_API_KEY: \${{ secrets.PEXELS_API_KEY }}
          IG_USER_ID: \${{ secrets.IG_USER_ID }}
          IG_ACCESS_TOKEN: \${{ secrets.IG_ACCESS_TOKEN }}
          RUN_URL: \${{ github.server_url }}/\${{ github.repository }}/actions/runs/\${{ github.run_id }}
        run: python -m autoposter cloud --mode "\${{ steps.due.outputs.mode }}" --slot "\${{ steps.due.outputs.slot }}"

      - if: always() && ${when}
        name: Save history
        run: |
          git config user.name "autoposter-bot"
          git config user.email "autoposter-bot@users.noreply.github.com"
          git add data/
          git diff --cached --quiet && exit 0
          git commit -q -m "Post history update"
          for i in 1 2 3; do git pull -q --rebase && git push -q && break; sleep 5; done

      - if: always() && ${when}
        name: Keep the video for 7 days
        uses: actions/upload-artifact@v4
        with:
          name: reel
          path: output/
          retention-days: 7
          if-no-files-found: ignore
`;
}

module.exports = { buildWorkflow, cronLines, tzOffsetMinutes };
