// Builds the GitHub Actions workflow. The cron lines are generated from the
// posting times in the panel (converted from local time to UTC, covering both
// summer and winter time so daylight saving changes never break the schedule).

function tzOffsetMinutes(timeZone, date) {
  const dtf = new Intl.DateTimeFormat("en-US", {
    timeZone, hourCycle: "h23", year: "numeric", month: "2-digit", day: "2-digit",
    hour: "2-digit", minute: "2-digit",
  });
  const p = Object.fromEntries(dtf.formatToParts(date).map((x) => [x.type, x.value]));
  const asUtc = Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour % 24, +p.minute);
  return Math.round((asUtc - date.getTime()) / 60000);
}

function cronLines(times, timeZone) {
  const year = new Date().getUTCFullYear();
  const offsets = [...new Set([0, 6].map((m) => tzOffsetMinutes(timeZone, new Date(Date.UTC(year, m, 15, 12)))))];
  const byMinute = new Map();
  for (const t of times) {
    const [h, m] = t.split(":").map(Number);
    for (const off of offsets) {
      const utc = (((h * 60 + m - off) % 1440) + 1440) % 1440;
      const minute = utc % 60;
      const hour = Math.floor(utc / 60);
      if (!byMinute.has(minute)) byMinute.set(minute, new Set());
      byMinute.get(minute).add(hour);
    }
  }
  const lines = [];
  for (const [minute, hours] of [...byMinute.entries()].sort((a, b) => a[0] - b[0])) {
    lines.push(`    - cron: "${minute} ${[...hours].sort((a, b) => a - b).join(",")} * * *"`);
  }
  return lines.length ? lines : ['    - cron: "0 0 1 1 *"'];
}

function buildWorkflow(settings) {
  // Precise posting is driven by the panel's scheduler (/api/tick, called every 5 min by an external cron).
  // GitHub's own schedule is only a backup (it is often late or skipped): every 3 hours, catches missed slots.
  const times = [...(settings.times || []), ...(settings.carousel_times || []), ...(settings.story_times || [])];
  const posting = ['    - cron: "23 */3 * * *"'];
  const c = settings.comments || {};
  const every = Math.max(1, Math.min(12, parseInt(c.every_hours, 10) || 1));
  const commentsCron = c.enabled === false ? [] : [`    - cron: "41 ${every === 1 ? "*" : "*/" + every} * * *"`];
  const crons = [...(times.length ? posting : []), ...commentsCron];
  if (!crons.length) crons.push('    - cron: "0 0 1 1 *"');
  const when = "steps.due.outputs.run == 'true'";
  const media = `${when} && steps.due.outputs.kind != 'comments'`;
  return `# Generated by the Velosyntech panel. Edit the schedule from the panel, not here.
name: Instagram auto-post
run-name: \${{ github.event_name == 'workflow_dispatch' && (inputs.mode == 'scheduled' && format('Programat - {0}', inputs.kind) || format('Manual - {0} {1}', inputs.kind, inputs.mode)) || 'Programat (rezervă)' }}

on:
  schedule:
${crons.join("\n")}
  workflow_dispatch:
    inputs:
      kind:
        description: "reel / carousel / story / comments"
        type: choice
        options: [reel, carousel, story, comments]
        default: reel
      mode:
        description: "now = postează acum, test = doar previzualizare (fără postare), scheduled = de la programator"
        type: choice
        options: [test, now, scheduled]
        default: test
      slot:
        description: "slot programat (completat automat)"
        type: string
        default: ""

permissions:
  contents: write

concurrency:
  group: \${{ ((github.event_name == 'schedule' && startsWith(github.event.schedule, '41 ')) || inputs.kind == 'comments') && 'ig-comments' || 'ig-post' }}
  cancel-in-progress: false

jobs:
  post:
    runs-on: ubuntu-latest
    timeout-minutes: 45
    steps:
      - uses: actions/checkout@v4

      - name: What to do now?
        id: due
        run: python3 -m autoposter.due "\${{ github.event_name }}" "\${{ inputs.mode }}" "\${{ inputs.kind }}" "\${{ github.event.schedule }}" "\${{ inputs.slot }}"

      - if: ${when}
        uses: actions/setup-python@v5
        with:
          python-version: "3.12"
          cache: pip

      - if: ${when}
        name: Install Python packages
        run: pip install -q -r requirements.txt

      - if: ${media}
        uses: actions/setup-node@v4
        with:
          node-version: "22"
          cache: npm
          cache-dependency-path: renderer/package-lock.json

      - if: ${media}
        name: Cache 3D browser
        uses: actions/cache@v4
        with:
          path: ~/.cache/ms-playwright
          key: playwright-\${{ hashFiles('renderer/package-lock.json') }}

      - if: ${media}
        name: Install video tools
        run: |
          APT="-o Acquire::Retries=2 -o Acquire::http::Timeout=20 -o Acquire::https::Timeout=20 -o DPkg::Lock::Timeout=60"
          timeout 150 sudo apt-get $APT update -qq || echo "::warning::apt update skipped"
          timeout 180 sudo apt-get $APT install -y -qq --no-install-recommends ffmpeg || echo "::warning::system ffmpeg skipped, using bundled one"
          cd renderer && npm ci --silent
          timeout 300 npx playwright install chromium
          # system libraries only if the browser can't start without them (needs apt, can be slow)
          node -e "import('playwright').then(p=>p.chromium.launch()).then(b=>b.close())" \\
            || timeout 420 npx playwright install --with-deps chromium

      - if: ${when}
        name: Run
        env:
          GEMINI_API_KEY: \${{ secrets.GEMINI_API_KEY }}
          GROQ_API_KEY: \${{ secrets.GROQ_API_KEY }}
          PEXELS_API_KEY: \${{ secrets.PEXELS_API_KEY }}
          IG_USER_ID: \${{ secrets.IG_USER_ID }}
          IG_ACCESS_TOKEN: \${{ secrets.IG_ACCESS_TOKEN }}
          FB_PAGE_ID: \${{ secrets.FB_PAGE_ID }}
          BLOB_READ_WRITE_TOKEN: \${{ secrets.BLOB_READ_WRITE_TOKEN }}
          RUN_URL: \${{ github.server_url }}/\${{ github.repository }}/actions/runs/\${{ github.run_id }}
        run: python -m autoposter cloud --kind "\${{ steps.due.outputs.kind }}" --mode "\${{ steps.due.outputs.mode }}" --slot "\${{ steps.due.outputs.slot }}"

      - if: always() && ${when}
        name: Save history
        run: |
          git config user.name "autoposter-bot"
          git config user.email "autoposter-bot@users.noreply.github.com"
          git add data/
          git diff --cached --quiet && exit 0
          git commit -q -m "Update history"
          for i in 1 2 3; do git pull -q --rebase && git push -q && break; sleep 5; done

      - if: always() && ${media}
        name: Keep the files for 7 days
        uses: actions/upload-artifact@v4
        with:
          name: output
          path: output/
          retention-days: 7
          if-no-files-found: ignore
`;
}

// ---------------------------------------------------------------- precise scheduler (used by /api/tick)
function localParts(timeZone, ms) {
  const p = Object.fromEntries(new Intl.DateTimeFormat("en-US", { timeZone, hourCycle: "h23", year: "numeric", month: "2-digit",
    day: "2-digit", hour: "2-digit", minute: "2-digit" }).formatToParts(new Date(ms)).map((x) => [x.type, x.value]));
  return { y: +p.year, m: +p.month, d: +p.day };
}

function slotInfo(timeZone, y, m, d, hhmm) {
  const [h, mi] = hhmm.split(":").map(Number);
  let utc = Date.UTC(y, m - 1, d, h, mi);
  const off = tzOffsetMinutes(timeZone, new Date(utc));
  utc -= off * 60000;
  const off2 = tzOffsetMinutes(timeZone, new Date(utc)); // DST edge
  if (off2 !== off) utc += (off - off2) * 60000;
  const o = tzOffsetMinutes(timeZone, new Date(utc)), sign = o >= 0 ? "+" : "-", a = Math.abs(o);
  const pad = (n) => String(n).padStart(2, "0");
  const iso = `${y}-${pad(m)}-${pad(d)}T${pad(h)}:${pad(mi)}:00${sign}${pad(Math.floor(a / 60))}:${pad(a % 60)}`;
  return { utc, iso };
}

const KIND_KEYS = [["reel", "times"], ["carousel", "carousel_times"], ["story", "story_times"]];
const WINDOW_MS = 3 * 3600 * 1000;

function dueSlots(settings, done, nowMs = Date.now()) {
  if (settings.paused) return [];
  const tz = settings.timezone || "Europe/Bucharest", doneSet = new Set(done || []);
  const out = [];
  for (const dayMs of [nowMs, nowMs - 86400000]) {
    const { y, m, d } = localParts(tz, dayMs);
    for (const [kind, key] of KIND_KEYS) {
      for (const t of settings[key] || []) {
        const s = slotInfo(tz, y, m, d, t), tag = `${kind}@${s.iso}`;
        if (s.utc <= nowMs && nowMs < s.utc + WINDOW_MS && !doneSet.has(tag) && !doneSet.has(s.iso)) out.push({ kind, tag, utc: s.utc });
      }
    }
  }
  return out.sort((a, b) => a.utc - b.utc);
}

module.exports = { buildWorkflow, cronLines, tzOffsetMinutes, dueSlots, slotInfo };
